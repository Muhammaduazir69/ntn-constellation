#!/usr/bin/env python3
"""Extra macros for the TAES correspondence (10 Nov 2026): per-run spread of the held-out loss prediction,
the share of the W_b term in the outage, and packet loss under ephemeris error. Reads out/pred_check.json
(written by make_macros_corr.py) and out/p7_v8.jsonl / p7_v9.jsonl; writes ../macros_p7_extra.tex."""
import json, os
H = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(H, "out")
rows = [json.loads(l) for fn in ("p7_v8.jsonl", "p7_v9.jsonl") for l in open(os.path.join(OUT, fn))]
P = json.load(open(os.path.join(OUT, "pred_check.json")))
M = {}
held = [p for p in P if p["kind"] == "held"]
M["PredRunErrMax"] = "%.0f" % (100 * max(max(abs(p["measlo"] - p["pred"]), abs(p["meashi"] - p["pred"])) / p["pred"] for p in held))
# W_b = W/2 against the whole outage (wait + t_a + W/2), largest over held-out trace runs
sh = []
for r in rows:
    if r.get("part") in ("htrace", "trace") and r.get("policy") in ("ondemand", "snap") and r.get("route_ms_mean") == r.get("route_ms_mean"):
        wait = 0.05 if r["policy"] == "ondemand" else 0.5
        W = r["route_ms_mean"] / 1e3
        sh.append(0.5 * W / (wait + 1.0 + 0.5 * W))
M["WbShareMax"] = "%.0f" % (100 * max(sh))
real = [p for p in held if p["c"][0] == "real_starlink16" and p["c"][1] == "lon-nyc" and p["pol"] == "Od"][0]
M["RealOdPred"], M["RealOdLo"], M["RealOdHi"] = "%.2f" % real["pred"], "%.2f" % real["measlo"], "%.2f" % real["meashi"]
def mx(pol, sig):
    v = [100 * r["loss"] for r in rows if r.get("part") == "pred" and not r.get("no_data") and r["policy"] == pol and r.get("pred_sigma_km") == sig]
    return "%.2f" % max(v), sum(x > 0 for x in v), len(v)
M["EphLifeTwenty"], a, b = mx("life", 20); M["EphLifeFive"], _, _ = mx("life", 5); M["EphAsrTwenty"], _, _ = mx("asr", 20)
M["EphLifeLostN"], M["EphLifeN"] = str(a), str(b)
with open(os.path.join(H, "..", "macros_p7_extra.tex"), "w") as f:
    f.write("%% generated by sim/make_macros_extra.py; do not edit\n")
    for k in sorted(M):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, M[k]))
print(M)
